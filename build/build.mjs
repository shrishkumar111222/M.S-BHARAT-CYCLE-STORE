#!/usr/bin/env node
/**
 * Static site build.
 *
 * Renders index.html from the component templates and bundles the modular
 * CSS into one stylesheet. Output is plain static files — GitHub Pages
 * serves them directly with no runtime build step.
 *
 *   node build/build.mjs
 */

import { writeFile, readFile, mkdir, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { setAvailablePhotos } from '../src/scripts/art.js';
import { BUSINESS } from '../src/scripts/config.js';
import { PRODUCTS, GALLERY, REVIEWS, SERVICES } from '../src/scripts/data.js';

import { header } from '../src/components/header.js';
import { hero } from '../src/components/hero.js';
import { features } from '../src/components/features.js';
import { brands } from '../src/components/brands.js';
import { products } from '../src/components/products.js';
import { services } from '../src/components/services.js';
import { gallery } from '../src/components/gallery.js';
import { reviews } from '../src/components/reviews.js';
import { stats } from '../src/components/stats.js';
import { location } from '../src/components/location.js';
import { cta, footer, dock } from '../src/components/footer.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Public origin — update if the site moves to a custom domain. */
const SITE_URL = process.env.SITE_URL || 'https://shrishkumar111222.github.io/m.s-bharat-cycle-store/';

/** "Sherghati, Gaya" — but just "Gaya" when the town is the district town. */
const PLACE =
  BUSINESS.city === BUSINESS.district
    ? `${BUSINESS.city}, ${BUSINESS.state}`
    : `${BUSINESS.city}, ${BUSINESS.district}`;

const DESCRIPTION =
  `${BUSINESS.name}, ${BUSINESS.street}, ${PLACE} — bicycle sales, kids ` +
  `ride-on cars and bikes, repairs and servicing, genuine spare parts and ` +
  `accessories. Hero, Atlas, Firefox, Avon, BSA, Hercules, Montra, kids and ` +
  `electric cycles.`;

/* ------------------------------------------------------------------ *
 * CSS bundle
 * ------------------------------------------------------------------ */

const CSS_FILES = [
  'src/styles/tokens.css',
  'src/styles/base.css',
  'src/styles/reveal.css',
  'src/components/header.css',
  'src/components/photo.css',
  'src/components/hero.css',
  'src/components/features.css',
  'src/components/brands.css',
  'src/components/products.css',
  'src/components/services.css',
  'src/components/gallery.css',
  'src/components/reviews.css',
  'src/components/stats.css',
  'src/components/location.css',
  'src/components/dock.css',
  'src/components/footer.css',
];

async function bundleCSS() {
  const parts = [];
  for (const file of CSS_FILES) {
    parts.push(`/* ===== ${file} ===== */\n${await readFile(join(ROOT, file), 'utf8')}`);
  }
  const css = `/*! ${BUSINESS.name} — generated by build/build.mjs. Edit the sources in src/, not this file. */\n${parts.join('\n')}`;
  await writeFile(join(ROOT, 'public/styles.css'), css);
  return css;
}

/* ------------------------------------------------------------------ *
 * Structured data
 * ------------------------------------------------------------------ */

const schema = () =>
  JSON.stringify(
    {
      '@context': 'https://schema.org',
      '@type': 'BicycleStore',
      '@id': `${SITE_URL}#store`,
      name: BUSINESS.name,
      description: DESCRIPTION,
      url: SITE_URL,
      telephone: BUSINESS.phone,
      priceRange: '₹₹',
      image: `${SITE_URL}public/images/og-cover.jpg`,
      address: {
        '@type': 'PostalAddress',
        streetAddress: BUSINESS.street,
        addressLocality: BUSINESS.city,
        addressRegion: BUSINESS.state,
        postalCode: BUSINESS.postalCode,
        addressCountry: BUSINESS.country,
      },
      geo: {
        '@type': 'GeoCoordinates',
        latitude: BUSINESS.lat,
        longitude: BUSINESS.lng,
      },
      openingHoursSpecification: BUSINESS.openingHours.map((h) => ({
        '@type': 'OpeningHoursSpecification',
        dayOfWeek: h.days.map(
          (d) =>
            ({
              Mo: 'Monday', Tu: 'Tuesday', We: 'Wednesday', Th: 'Thursday',
              Fr: 'Friday', Sa: 'Saturday', Su: 'Sunday',
            })[d]
        ),
        opens: h.opens,
        closes: h.closes,
      })),
      hasMap: BUSINESS.mapsPlaceUrl,
      makesOffer: PRODUCTS.map((p) => ({
        '@type': 'Offer',
        itemOffered: { '@type': 'Product', name: p.name, description: p.desc },
        priceCurrency: 'INR',
        price: p.price.replace(/[₹,]/g, ''),
        availability: 'https://schema.org/InStock',
      })),
      // Service list, so search engines can surface the workshop offering.
      hasOfferCatalog: {
        '@type': 'OfferCatalog',
        name: 'Repairs & Servicing',
        itemListElement: SERVICES.map((s) => ({
          '@type': 'Offer',
          itemOffered: { '@type': 'Service', name: s.name, description: s.detail },
        })),
      },
    },
    null,
    2
  );

/* NOTE: AggregateRating is deliberately omitted. Google's structured-data
   policy requires ratings to be genuine and collected by the site itself;
   the demo testimonials in data.js are not. Add it back only once real
   review data is in place. */

/* ------------------------------------------------------------------ *
 * Page
 * ------------------------------------------------------------------ */

